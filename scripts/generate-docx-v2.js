function h1(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: fontH, size: 36, bold: true, color: CHARCOAL })],
    spacing: { before: 480, after: 240 }, heading: HeadingLevel.HEADING_1
  });
}
function h2(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: fontH, size: 28, bold: true, color: CRIMSON })],
    spacing: { before: 360, after: 180 }, heading: HeadingLevel.HEADING_2
  });
}
function h3(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: fontH, size: 24, bold: true, color: CHARCOAL })],
    spacing: { before: 240, after: 120 }, heading: HeadingLevel.HEADING_3
  });
}
function para(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, font: fontB, size: 21, color: opts.color || CHARCOAL, ...opts })],
    spacing: { after: 100 }, alignment: opts.align || AlignmentType.JUSTIFIED
  });
}
function bold(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, font: fontB, size: 21, bold: true, color: opts.color || CHARCOAL, ...opts })],
    spacing: { after: 80 }, alignment: opts.align || AlignmentType.LEFT
  });
}
function bul(text, lvl = 0) {
  return new Paragraph({
    children: [new TextRun({ text, font: fontB, size: 21, color: CHARCOAL })],
    spacing: { after: 40 }, bullet: { level: lvl },
    indent: { left: convertInchesToTwip(0.4 + lvl * 0.25) }
  });
}
function sp() { return new Paragraph({ children: [], spacing: { after: 60 } }); }
function pb() { return new Paragraph({ children: [new PageBreak()] }); }
function div() {
  return new Paragraph({ children: [], border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: "D4D0C8" } }, spacing: { before: 80, after: 80 } });
}

function cell(text, w, opts = {}) {
  return new TableCell({
    children: [new Paragraph({ children: [new TextRun({ text: String(text), font: fontB, size: 18, color: opts.color || CHARCOAL, bold: opts.bold })], alignment: opts.align || AlignmentType.LEFT })],
    width: { size: w, type: WidthType.PERCENTAGE },
    borders: { top: thinBorder, bottom: thinBorder, left: thinBorder, right: thinBorder },
    shading: opts.bg ? { type: ShadingType.SOLID, color: opts.bg } : undefined,
    verticalAlign: "center"
  });
}
function hdr(text, w) {
  return new TableCell({
    children: [new Paragraph({ children: [new TextRun({ text, font: fontB, size: 18, bold: true, color: WHITE })], alignment: AlignmentType.CENTER })],
    width: { size: w, type: WidthType.PERCENTAGE },
    shading: { type: ShadingType.SOLID, color: CRIMSON },
    verticalAlign: "center"
  });
}
function tbl(headers, rows, widths) {
  const hr = new TableRow({ children: headers.map((h, i) => hdr(h, widths[i])) });
  const dr = rows.map((r, ri) => new TableRow({ children: r.map((c, ci) => cell(c, widths[ci], { bg: ri % 2 === 1 ? LIGHT_BG : undefined })) }));
  return new Table({ rows: [hr, ...dr], width: { size: 100, type: WidthType.PERCENTAGE }, borders: { top: noBorder, bottom: noBorder, left: noBorder, right: noBorder, insideHorizontal: thinBorder, insideVertical: thinBorder } });
}

